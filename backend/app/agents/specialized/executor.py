"""
Executor Agent

Specialised agent responsible for executing plans generated by the
PlannerAgent.  It resolves dependency ordering, delegates tool calls
to the ToolRegistry, tracks per-step execution status, and stores
results in AgentState.

Responsibilities
----------------
* Topologically sort plan steps by their ``depends_on`` edges.
* Execute each step (tool call or reasoning) with retry + timeout.
* Record every attempt in an :class:`ExecutionRecord` history.
* Populate ``AgentState.results``, ``tools_used``, and ``errors``.
* Handle failures gracefully — skip dependents of failed steps.
"""

import asyncio
import time
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Dict, List, Optional

import structlog

from app.agents.base import AgentConfig, BaseAgent
from app.models.agent import AgentStatus, AgentType
from app.models.execution import ExecutionRecord, ExecutionResult, ExecutionStatus
from app.models.state import AgentState, PlanStep
from app.models.tool import ToolExecutionRequest, ToolPermission

if TYPE_CHECKING:
    from app.tools.registry import ToolRegistry


# ── Constants ────────────────────────────────────────────────────

DEFAULT_STEP_TIMEOUT: int = 30
DEFAULT_MAX_RETRIES: int = 3
DEFAULT_RETRY_DELAY: float = 1.0
DEFAULT_RETRY_BACKOFF: float = 2.0


# ── Exceptions ───────────────────────────────────────────────────


class StepExecutionError(Exception):
    """Raised when a single plan step fails after all retries."""

    def __init__(self, step_index: int, message: str) -> None:
        self.step_index = step_index
        super().__init__(f"Step {step_index} failed: {message}")


class DependencyResolutionError(Exception):
    """Raised when dependency ordering fails (cycle or missing index)."""


class ExecutionTimeoutError(Exception):
    """Raised when a step exceeds its timeout budget."""


# ── ExecutorAgent ─────────────────────────────────────────────────


class ExecutorAgent(BaseAgent):
    """
    Agent that executes a plan produced by the PlannerAgent.

    Parameters
    ----------
    config : AgentConfig | None
        Agent configuration.  ``type`` defaults to ``EXECUTOR``.
    tool_registry : ToolRegistry | None
        Registry used to resolve and invoke tools.  When ``None``
        tool steps are recorded but not actually executed.
    max_retries : int
        Maximum retry attempts per step (default 3).
    default_timeout : int
        Default per-step timeout in seconds (default 30).
    """

    def __init__(
        self,
        config: Optional[AgentConfig] = None,
        tool_registry: Optional["ToolRegistry"] = None,
        max_retries: int = DEFAULT_MAX_RETRIES,
        default_timeout: int = DEFAULT_STEP_TIMEOUT,
    ) -> None:
        if config is None:
            config = AgentConfig(
                name="ExecutorAgent",
                type=AgentType.EXECUTOR,
                description="Executes plans with tools and records results.",
            )
        super().__init__(config)
        self.tool_registry = tool_registry
        self.max_retries = max_retries
        self.default_timeout = default_timeout
        self.execution_history: List[ExecutionRecord] = []
        self.logger = self.logger.bind(component="executor_agent")

    # ── BaseAgent interface ───────────────────────────────────

    async def process(self, input_data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Execute a plan and return structured results.

        Parameters
        ----------
        input_data : dict
            Must contain ``"state"`` (:class:`AgentState`) with a
            populated ``plan``.  May also contain:
            - ``"tool_registry"`` (:class:`ToolRegistry`) – override

        Returns
        -------
        dict
            ``{"success": bool, "results": list[dict], "errors": list[str],
              "tools_used": list[str], "execution_history": list[dict]}``
        """
        state: AgentState = input_data.get("state")
        if state is None:
            return {
                "success": False,
                "results": [],
                "errors": ["No AgentState provided."],
                "tools_used": [],
                "execution_history": [],
            }

        registry: Optional["ToolRegistry"] = (
            input_data.get("tool_registry") or self.tool_registry
        )

        try:
            results, errors, tools_used, records = await self._execute_plan(
                state.plan, registry
            )
        except DependencyResolutionError as exc:
            return {
                "success": False,
                "results": [],
                "errors": [str(exc)],
                "tools_used": [],
                "execution_history": [],
            }

        success = len(errors) == 0

        # Store results in AgentState
        state.results.extend(results)
        state.errors.extend(errors)
        state.tools_used.extend(tools_used)

        self.execution_history.extend(records)

        self.update_memory("last_results", [r.model_dump() for r in results])
        self.update_memory("last_errors", errors)

        self.logger.info(
            "Plan execution finished",
            total_steps=len(state.plan),
            successes=len([r for r in results if r.success]),
            failures=len(errors),
            tools_used=len(tools_used),
        )

        return {
            "success": success,
            "results": [r.model_dump() for r in results],
            "errors": errors,
            "tools_used": tools_used,
            "execution_history": [rec.to_dict() for rec in records],
        }

    async def reflect(self, result: Dict[str, Any]) -> Dict[str, Any]:
        """
        Reflect on the execution result.

        Parameters
        ----------
        result : dict
            The result dict returned by :meth:`process`.

        Returns
        -------
        dict
            Reflection insights.
        """
        results = result.get("results", [])
        errors = result.get("errors", [])
        tools_used = result.get("tools_used", [])
        execution_history = result.get("execution_history", [])

        successes = sum(1 for r in results if r.get("success"))
        failures = len(results) - successes

        total_time = sum(
            r.get("execution_time_ms", 0) for r in results
        )

        retries = sum(
            r.get("retry_count", 0) for r in execution_history
        )

        insights: Dict[str, Any] = {
            "total_steps": len(results),
            "successful_steps": successes,
            "failed_steps": failures,
            "unique_tools_used": list(set(tools_used)),
            "total_execution_time_ms": total_time,
            "total_retries": retries,
            "overall_success": result.get("success", False),
        }

        if execution_history:
            statuses = [r.get("status") for r in execution_history]
            insights["status_distribution"] = {
                s: statuses.count(s) for s in set(statuses)
            }

        self.logger.info("Executor reflection", **insights)
        self.update_memory("last_reflection", insights)
        return insights

    # ── Dependency ordering ────────────────────────────────────

    @staticmethod
    def _resolve_execution_order(steps: List[PlanStep]) -> List[PlanStep]:
        """
        Topologically sort plan steps by their ``depends_on`` edges.

        Steps with no dependencies come first, then steps whose
        dependencies have all been scheduled.

        Raises
        ------
        DependencyResolutionError
            If a cycle is detected or a dependency references a
            non-existent step index.
        """
        if not steps:
            return []

        index_map: Dict[int, PlanStep] = {s.index: s for s in steps}
        indices = set(index_map.keys())

        # Validate all dependency references exist
        for step in steps:
            for dep in step.depends_on:
                if dep not in indices:
                    raise DependencyResolutionError(
                        f"Step {step.index} depends on non-existent step {dep}"
                    )

        # Kahn's algorithm for topological sort
        in_degree: Dict[int, int] = {s.index: 0 for s in steps}
        dependents: Dict[int, List[int]] = {s.index: [] for s in steps}

        for step in steps:
            for dep in step.depends_on:
                in_degree[step.index] += 1
                dependents[dep].append(step.index)

        queue: List[int] = [idx for idx, deg in in_degree.items() if deg == 0]
        order: List[int] = []

        while queue:
            queue.sort()  # deterministic: lower index first
            idx = queue.pop(0)
            order.append(idx)
            for dependent in dependents[idx]:
                in_degree[dependent] -= 1
                if in_degree[dependent] == 0:
                    queue.append(dependent)

        if len(order) != len(steps):
            remaining = [idx for idx in index_map if idx not in order]
            raise DependencyResolutionError(
                f"Dependency cycle detected involving steps: {remaining}"
            )

        return [index_map[idx] for idx in order]

    # ── Internal execution engine ──────────────────────────────

    async def _execute_plan(
        self,
        plan: List[PlanStep],
        registry: Optional["ToolRegistry"],
    ) -> tuple[
        List[ExecutionResult],
        List[str],
        List[str],
        List[ExecutionRecord],
    ]:
        """
        Execute every step in dependency order.

        Returns
        -------
        (results, errors, tools_used, records)
        """
        results: List[ExecutionResult] = []
        errors: List[str] = []
        tools_used: List[str] = []
        records: List[ExecutionRecord] = []

        failed_indices: set = set()

        try:
            ordered_steps = self._resolve_execution_order(plan)
        except DependencyResolutionError as exc:
            raise exc

        for step in ordered_steps:
            # Skip if any dependency failed
            if any(dep in failed_indices for dep in step.depends_on):
                record = ExecutionRecord(
                    step_index=step.index,
                    description=step.description,
                    tool_name=step.tool_name,
                )
                record.mark_skipped(
                    reason=f"Skipped due to failed dependency"
                )
                records.append(record)
                self.logger.info(
                    "Step skipped (dependency failed)",
                    step_index=step.index,
                )
                continue

            record = ExecutionRecord(
                step_index=step.index,
                description=step.description,
                tool_name=step.tool_name,
            )
            record.mark_started()
            records.append(record)

            step_result = await self._execute_step(step, registry, record)

            results.append(step_result)

            if step_result.tool_name and step_result.tool_name not in tools_used:
                tools_used.append(step_result.tool_name)

            if step_result.success:
                record.mark_completed(step_result)
                self.logger.info(
                    "Step executed successfully",
                    step_index=step.index,
                    tool_name=step.tool_name,
                    execution_time_ms=step_result.execution_time_ms,
                )
            else:
                error_msg = step_result.error or "Unknown error"
                if step_result.timeout:
                    record.mark_timed_out(error_msg)
                else:
                    record.mark_failed(step_result, error_msg)
                errors.append(
                    f"Step {step.index}: {error_msg}"
                )
                failed_indices.add(step.index)
                self.logger.warning(
                    "Step execution failed",
                    step_index=step.index,
                    error=error_msg,
                )

        return results, errors, tools_used, records

    async def _execute_step(
        self,
        step: PlanStep,
        registry: Optional["ToolRegistry"],
        record: ExecutionRecord,
    ) -> ExecutionResult:
        """
        Execute a single plan step with retry and timeout.

        Parameters
        ----------
        step : PlanStep
            The step to execute.
        registry : ToolRegistry | None
            Tool registry for tool invocations.
        record : ExecutionRecord
            Execution record to update on retry.

        Returns
        -------
        ExecutionResult
            The final result after all retry attempts.
        """
        last_error: Optional[str] = None
        last_was_timeout: bool = False
        timeout = self.default_timeout
        step_timeout = step.tool_parameters.pop("_timeout", None)
        if isinstance(step_timeout, (int, float)) and step_timeout > 0:
            timeout = int(step_timeout)

        for attempt in range(1, self.max_retries + 1):
            step_start = time.monotonic()

            try:
                if step.tool_name:
                    result = await self._execute_tool_step(
                        step, registry, timeout
                    )
                else:
                    result = await self._execute_reasoning_step(step)

                elapsed_ms = (time.monotonic() - step_start) * 1000
                result.execution_time_ms = elapsed_ms
                result.retry_count = attempt - 1

                if result.success:
                    return result

                # Failed but not an exception — record and retry
                last_error = result.error or "Tool returned failure"
                last_was_timeout = False
                record.attempts.append(result)

                if attempt < self.max_retries:
                    record.mark_retrying()
                    self.logger.warning(
                        "Step failed, retrying",
                        step_index=step.index,
                        attempt=attempt,
                        max_retries=self.max_retries,
                        error=last_error,
                    )
                    await self._async_sleep(
                        DEFAULT_RETRY_DELAY * (DEFAULT_RETRY_BACKOFF ** (attempt - 1))
                    )

            except asyncio.TimeoutError:
                elapsed_ms = (time.monotonic() - step_start) * 1000
                error_msg = f"Step timed out after {timeout}s"
                result = ExecutionResult(
                    step_index=step.index,
                    tool_name=step.tool_name,
                    success=False,
                    error=error_msg,
                    execution_time_ms=elapsed_ms,
                    timeout=True,
                )
                record.attempts.append(result)
                last_error = error_msg
                last_was_timeout = True

                if attempt < self.max_retries:
                    record.mark_retrying()
                    self.logger.warning(
                        "Step timed out, retrying",
                        step_index=step.index,
                        attempt=attempt,
                        timeout=timeout,
                    )
                    await self._async_sleep(
                        DEFAULT_RETRY_DELAY * (DEFAULT_RETRY_BACKOFF ** (attempt - 1))
                    )

            except Exception as exc:
                elapsed_ms = (time.monotonic() - step_start) * 1000
                error_msg = f"{type(exc).__name__}: {exc}"
                result = ExecutionResult(
                    step_index=step.index,
                    tool_name=step.tool_name,
                    success=False,
                    error=error_msg,
                    execution_time_ms=elapsed_ms,
                )
                record.attempts.append(result)
                last_error = error_msg
                last_was_timeout = False

                self.logger.error(
                    "Step raised exception",
                    step_index=step.index,
                    attempt=attempt,
                    error=error_msg,
                )

                if attempt < self.max_retries:
                    record.mark_retrying()
                    await self._async_sleep(
                        DEFAULT_RETRY_DELAY * (DEFAULT_RETRY_BACKOFF ** (attempt - 1))
                    )

        # All retries exhausted
        return ExecutionResult(
            step_index=step.index,
            tool_name=step.tool_name,
            success=False,
            error=f"Failed after {self.max_retries} attempts: {last_error}",
            execution_time_ms=0,
            retry_count=self.max_retries - 1,
            timeout=last_was_timeout,
        )

    async def _execute_tool_step(
        self,
        step: PlanStep,
        registry: Optional["ToolRegistry"],
        timeout: int,
    ) -> ExecutionResult:
        """Execute a plan step that invokes a tool."""
        if registry is None:
            return ExecutionResult(
                step_index=step.index,
                tool_name=step.tool_name,
                success=False,
                error=f"No tool registry available to execute '{step.tool_name}'",
            )

        tool = registry.get_tool(step.tool_name)
        if tool is None:
            return ExecutionResult(
                step_index=step.index,
                tool_name=step.tool_name,
                success=False,
                error=f"Tool '{step.tool_name}' not found in registry",
            )

        request = ToolExecutionRequest(
            tool_name=step.tool_name,
            parameters=step.tool_parameters,
            timeout=timeout,
            agent_permissions=[
                ToolPermission.READ,
                ToolPermission.WRITE,
                ToolPermission.EXECUTE,
                ToolPermission.NETWORK,
                ToolPermission.FILE_SYSTEM,
                ToolPermission.DATABASE,
            ],
        )

        tool_result = await asyncio.wait_for(
            registry.execute(request),
            timeout=timeout,
        )

        return ExecutionResult(
            step_index=step.index,
            tool_name=step.tool_name,
            success=tool_result.success,
            output=tool_result.output,
            error=tool_result.error,
            execution_time_ms=tool_result.execution_time,
        )

    async def _execute_reasoning_step(self, step: PlanStep) -> ExecutionResult:
        """Execute a plan step that requires no tool (LLM reasoning placeholder)."""
        output = (
            f"Step {step.index} completed "
            f"(reasoning: {step.description})"
        )
        return ExecutionResult(
            step_index=step.index,
            tool_name=None,
            success=True,
            output=output,
        )

    # ── Helpers ───────────────────────────────────────────────

    @staticmethod
    async def _async_sleep(seconds: float) -> None:
        """Async sleep wrapper for testability."""
        await asyncio.sleep(seconds)

    def get_execution_history(
        self,
        step_index: Optional[int] = None,
    ) -> List[ExecutionRecord]:
        """
        Retrieve execution history, optionally filtered by step index.

        Parameters
        ----------
        step_index : int | None
            If provided, only return records for this step index.

        Returns
        -------
        list[ExecutionRecord]
        """
        if step_index is not None:
            return [r for r in self.execution_history if r.step_index == step_index]
        return list(self.execution_history)

    def get_execution_stats(self) -> Dict[str, Any]:
        """
        Get aggregate execution statistics.

        Returns
        -------
        dict
            Statistics including total steps, successes, failures, retries.
        """
        total = len(self.execution_history)
        completed = sum(
            1 for r in self.execution_history
            if r.status == ExecutionStatus.COMPLETED
        )
        failed = sum(
            1 for r in self.execution_history
            if r.status in (ExecutionStatus.FAILED, ExecutionStatus.TIMED_OUT)
        )
        skipped = sum(
            1 for r in self.execution_history
            if r.status == ExecutionStatus.SKIPPED
        )
        total_retries = sum(
            len(r.attempts) - 1 if r.attempts else 0
            for r in self.execution_history
        )

        return {
            "total_steps": total,
            "completed": completed,
            "failed": failed,
            "skipped": skipped,
            "total_retries": total_retries,
        }
